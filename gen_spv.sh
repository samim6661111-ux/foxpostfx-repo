#!/usr/bin/env bash
# usage: tools/gen_spv.sh <glslc> <outdir>
# compiles every shaders/*.{vert,frag} to a C array (.inc) and writes spv_shaders.h
set -euo pipefail
GLSLC="${1:?glslc path}"; OUT="${2:?out dir}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$OUT"
H="$OUT/spv_shaders.h"
{ echo "// generated by tools/gen_spv.sh - do not edit"; echo "#pragma once"; echo "#include <stdint.h>"; } > "$H"
for f in "$ROOT"/*.vert "$ROOT"/*.frag; do
  b="$(basename "$f")"; n="${b//./_}"
  "$GLSLC" -O --target-env=vulkan1.0 -mfmt=c "$f" -o "$OUT/$n.inc"
  { echo "static const uint32_t ${n}_spv[] ="; echo "#include \"$n.inc\""; echo ";"; } >> "$H"
  echo "compiled $b"
done
